// Validator: resource identity must survive export / alias so own / borrow and
// canon resource.* on the surfaced type resolve. Each case loads + validates a
// component; valid cases must pass, the locality case must still be rejected.

// Exporting a resource type creates an alias index; own + resource.drop on the
// exported slot must validate (resource identity propagated to the export).
//   (type $r' (resource (rep i32))) (export $r "r" (type $r'))
//   (func (export "f") (param "x" (own $r)) (canon lift (canon resource.drop
//   $r)))
TEST(ComponentResourceValidate, ExportedResourceOwnDrop) {
  auto VM = makeResourceVM();
  std::vector<uint8_t> Vec = {
      0x00, 0x61, 0x73, 0x6d, 0x0d, 0x00, 0x01, 0x00, 0x07, 0x04, 0x01, 0x3f,
      0x7f, 0x00, 0x0b, 0x07, 0x01, 0x00, 0x01, 0x72, 0x03, 0x00, 0x00, 0x08,
      0x03, 0x01, 0x03, 0x01, 0x07, 0x0a, 0x02, 0x69, 0x01, 0x40, 0x01, 0x01,
      0x78, 0x02, 0x01, 0x00, 0x08, 0x06, 0x01, 0x00, 0x00, 0x00, 0x00, 0x03,
      0x0b, 0x07, 0x01, 0x00, 0x01, 0x66, 0x01, 0x00, 0x00, 0x00, 0x29, 0x0e,
      0x63, 0x6f, 0x6d, 0x70, 0x6f, 0x6e, 0x65, 0x6e, 0x74, 0x2d, 0x6e, 0x61,
      0x6d, 0x65, 0x01, 0x06, 0x00, 0x00, 0x01, 0x00, 0x01, 0x66, 0x01, 0x10,
      0x03, 0x04, 0x00, 0x02, 0x72, 0x27, 0x01, 0x01, 0x72, 0x02, 0x01, 0x6f,
      0x03, 0x02, 0x66, 0x74};
  ASSERT_TRUE(VM.loadWasm(Vec));
  EXPECT_TRUE(VM.validate());
}

// Inline-exporting a resource through an instance, then alias-exporting it
// back, must preserve identity so own + resource.drop on the aliased slot
// validate.
//   (instance $i' (export "r" (type $r'))) (export "i" (instance $i'))
