// Import / export annotated-name direction (Binary.md "annotated names", the
// "respectively" rule): a [constructor]/[method]/[static] export must match a
// preceding resource *export* in the same scope, not merely any resource in
// scope. Cross-checked against wasm-tools 1.251 (reference implementation).

// A [method]r export whose resource r is only *imported* must be rejected: the
// annotated name has no matching resource export in this scope. wasm-tools
// rejects the same binary ("resource used in function does not have a name in
// this context").
//   (component (type (component
//     (import "r" (type $r (sub resource)))
//     (type $ft (func (param "self" (borrow $r))))
